export const buildDemoStore = (): MarketHubStore => ({
  version: STORE_VERSION,
  opportunities: OPPORTUNITIES,
  campaigns: CAMPAIGNS,
  workspacePlans: { ...DEFAULT_PLANS },
  credits: Object.fromEntries(
    Object.entries(DEFAULT_PLANS).map(([ws, plan]) => {
      const used = CAMPAIGNS.filter((c) => c.ownerWorkspaceId === ws).reduce((n, c) => n + (c.creditsUsed ?? 0), 0);
      return [ws, { available: Math.max(0, PLANS[plan].entitlements.monthlyCredits - used), used }];
    })
  ),
  buyerPrefs: structuredClone(DEFAULT_BUYER_PREFS),
  mutedBySupplier: {},
});
