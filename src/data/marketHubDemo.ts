const response = (id: string, responderId: string, c: Partial<CampaignResponse>, ago: number): CampaignResponse => {
  const r = supplierRecipient(responderId)!;
  return {
    id,
    responderId,
    companyName: r.companyName,
    category: r.categories[0],
    location: r.emirate,
    verified: r.verified,
    message: 'Material available from local stock. Technical data sheet attached.',
    availability: 'available',
    leadTime: '5–7 days',
    at: daysAgo(ago),
    shortlisted: false,
    connectRequested: false,
    demo: true,
    ...c,
  };
};

const wpResponders = SUPPLIER_POOL.filter((s) => s.categories.includes('Waterproofing') && s.id !== 'ws_apex_castings').slice(0, 12);

const campaign = (c: Partial<Campaign> & Pick<Campaign, 'id' | 'kind' | 'title' | 'category' | 'subcategory' | 'description' | 'ownerWorkspaceId' | 'ownerCompany' | 'status'>): Campaign => {
  const base: Campaign = {
    identity: 'public',
    responseDeadline: daysAhead(10),
    createdAt: daysAgo(10),
    estimatedAudience: 0,
    creditsRequired: 0,
    events: [],
    responses: [],
    ...c,
  };
  const ids = audienceIds(base, DEFAULT_BUYER_PREFS);
  base.estimatedAudience = ids.length;
  base.creditsRequired = creditsFor(ids.length);
  if (['active', 'completed', 'suspended'].includes(base.status) && !base.recipientIds) {
    base.recipientIds = ids;
    base.delivered = ids.length;
    base.creditsUsed = base.creditsRequired;
  }
  return base;
};

